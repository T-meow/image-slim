export const copy: Record<Language, Messages> = { zh, en };

export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function errorText(error: AppError, messages: Messages): string {
  return interpolate(messages.errorMessages[error.code], error.params);
}
